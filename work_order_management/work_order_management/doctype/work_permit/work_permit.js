const wp_esc = (t) => frappe.utils.escape_html(t || "");

// ------------------------------------------------------------------ tracker chips
function wp_done(frm, f) {
	if (f === "valid_until" && frm.doc.valid_until_work_complete) return true;
	const v = frm.doc[f];
	return !!(v && String(v).trim());
}

function wp_chips(frm) {
	const ur = wp_lang() === "ur";
	const names = ur ? WP_UR.chips : WP_EN_CHIPS;
	let $bar = $(frm.wrapper).find(".wp-chips");
	if (!$bar.length) {
		const $tabs = $(frm.wrapper).find(".form-tabs-list");
		if (!$tabs.length) return;
		$bar = $(`<div class="wp-chips"></div>`).insertBefore($tabs);
		$tabs.addClass("wp-hide-tabs");
		$bar.on("click", ".wp-chip", (e) => {
			const tab = WP_TABS[$(e.currentTarget).data("i")];
			const t = (frm.layout.tabs || []).find((x) => x.df && x.df.fieldname === tab);
			if (t && t.set_active) t.set_active();
			else $(frm.wrapper).find(`.form-tabs-list .nav-link[data-fieldname="${tab}"]`).trigger("click");
			window.scrollTo({ top: 0 });
			wp_mark_active(frm);
		});
	}
	const active = wp_active_tab(frm);
	$bar.attr("dir", ur ? "rtl" : "ltr").html(WP_REQ.map((list, i) => {
		const done = list.filter((f) => wp_done(frm, f)).length, all = done === list.length;
		return `<button type="button" class="wp-chip ${all ? "done" : ""} ${active === i ? "on" : ""}" data-i="${i}">
			<span class="cn">${all ? "&#10003;" : i + 1}</span>
			<span class="ct"><b>${wp_esc(names[i])}</b><small>${done}/${list.length}</small></span></button>`;
	}).join(""));
}

function wp_active_tab(frm) {
	const $links = $(frm.wrapper).find(".form-tabs-list .nav-link");
	let idx = 0;
	$links.each((i, a) => { if ($(a).hasClass("active")) idx = i; });
	return idx;
}
function wp_mark_active(frm) {
	setTimeout(() => {
		const a = wp_active_tab(frm);
		$(frm.wrapper).find(".wp-chip").each((i, c) => $(c).toggleClass("on", i === a));
	}, 50);
}

