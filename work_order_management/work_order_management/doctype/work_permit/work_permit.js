function wp_colors(frm) {
	const ur = wp_lang() === "ur";
	let $bar = $(frm.wrapper).find(".wp-colors");
	if (!$bar.length) {
		const $chips = $(frm.wrapper).find(".wp-chips");
		if (!$chips.length) return;
		$bar = $(`<div class="wp-colors"></div>`).insertBefore($chips);
		$bar.on("click", ".wp-color", (e) => {
			if (frm.doc.docstatus === 2) return;
			const v = $(e.currentTarget).data("v");
			frm.set_value("permit_color", frm.doc.permit_color === v ? "" : v);
		});
	}
	const sel = frm.doc.permit_color;
	const c = WP_COLORS.find((x) => x[0] === sel);
	$bar.attr("dir", ur ? "rtl" : "ltr").html(
		`<span class="wp-color-l">${ur ? "پرمٹ کا رنگ" : "Permit colour"}</span>` +
		WP_COLORS.map(([v, hex, u]) => `<button type="button" class="wp-color ${sel === v ? "on" : ""}" data-v="${v}"
			style="--c:${hex}" aria-pressed="${sel === v}"><i></i>${ur ? u : v}</button>`).join("") +
		`<span class="wp-color-sel">${c ? (ur ? "منتخب: " + c[2] : "Selected: " + c[0]) : (ur ? "کوئی رنگ منتخب نہیں" : "No colour chosen")}</span>`);
	// the chosen colour also shows as a band on top of the form
	$(frm.wrapper).find(".form-layout").css("border-top", c ? `6px solid ${c[1]}` : "");
}

// ------------------------------------------------------------------ language
function wp_decl(tag, text) {
	return `<div class="wp-decl"><span class="wp-decl-tag">${wp_esc(tag)}</span><p>${wp_esc(text)}</p></div>`;
}

function wp_apply(frm) {
	const ur = wp_lang() === "ur";
	if (!frm.wp_en) {
		frm.wp_en = {};
		frm.meta.fields.forEach((df) => { frm.wp_en[df.fieldname] = { label: df.label, description: df.description, options: df.options }; });
	}
	Object.keys(WP_UR.sections).forEach((f) => {
		const sec = frm.fields_dict[f], en = frm.wp_en[f];
		if (!sec || !en) return;
		const [l, d] = ur ? WP_UR.sections[f] : [en.label, en.description];
		if (sec.head && l) {
			const ind = sec.head.find(".collapse-indicator").detach();
			sec.head.text(l).append(ind);
		}
		if (sec.description_wrapper && d) sec.description_wrapper.text(d);
	});
	Object.keys(WP_UR.labels).forEach((f) => {
		const en = frm.wp_en[f];
		if (!en) return;
		const text = ur ? WP_UR.labels[f] : en.label;
		frm.set_df_property(f, "label", text);
		const fld = frm.get_field(f);
		if (fld && fld.df.fieldtype === "Signature") fld.$wrapper.find(".control-label, .label").first().text(text);
	});
	frm.meta.fields.filter((df) => df.fieldtype === "Select").forEach((df) => {
		const opts = (frm.wp_en[df.fieldname].options || "").split("\n").map((v) => ({ value: v, label: ur ? (WP_UR.options[v] || v) : v }));
		frm.set_df_property(df.fieldname, "options", opts);
	});
	["declaration_1", "declaration_2"].forEach((f) => {
		const [tag, text] = ur ? WP_UR.notes[f] : WP_EN_NOTE[f];
		frm.get_field(f) && frm.get_field(f).$wrapper.html(wp_decl(tag, text));
	});
	const st = frm.get_field("hse_statement");
	if (st) st.$wrapper.html(`<p class="wp-stmt">&#10003; ${wp_esc(ur ? WP_UR.notes.hse_statement : WP_EN_NOTE.hse_statement)}</p>`);
	$(frm.wrapper).find(".form-layout").attr("dir", ur ? "rtl" : "ltr").toggleClass("wp-ur", ur);
	// text boxes: Urdu typing + right-to-left
	frm.meta.fields.filter((df) => WP_TYPE_URDU.includes(df.fieldtype)).forEach((df) => {
		const fld = frm.get_field(df.fieldname);
		if (!fld || !fld.$input) return;
		fld.$input.attr({ dir: ur ? "rtl" : "auto", lang: ur ? "ur" : "en" }).toggleClass("wp-type-ur", ur);
	});
	wp_chips(frm);
	wp_colors(frm);
}

function wp_keyboard(frm) {
	if (frm.wp_keys_bound) return;
	frm.wp_keys_bound = true;
	$(frm.wrapper).on("keydown", "input.wp-type-ur, textarea.wp-type-ur", (e) => {
		if (e.ctrlKey || e.altKey || e.metaKey || e.key.length !== 1) return;
		const ch = WP_KEYS[e.key];
		if (!ch) return;
		e.preventDefault();
		if (!document.execCommand("insertText", false, ch)) {   // fallback
			const el = e.target, s = el.selectionStart, t = el.selectionEnd;
			el.value = el.value.slice(0, s) + ch + el.value.slice(t);
			el.selectionStart = el.selectionEnd = s + ch.length;
			$(el).trigger("input");
		}
	});
}

